def load_result_rows(paths: List[Path]) -> List[Dict[str, Any]]:
    rows = []
    for path in paths:
        if not path.is_file() or path.stat().st_size == 0:
            fail(f"missing result for report: {path}")
        with path.open() as stream:
            rows.append(json.load(stream))
    return rows


def paired_stats(
    control: str,
    treatment: str,
    a_runs: List[Dict[str, Any]],
    b_runs: List[Dict[str, Any]],
) -> Dict[str, Any]:
    all_runs = a_runs + b_runs
    recording_sets = [frozenset(row["per_recording"]) for row in all_runs]
    if len(set(recording_sets)) != 1:
        fail(
            f"{treatment} vs {control}: recording sets differ; paired "
            "intersection is forbidden"
        )
    recordings = sorted(recording_sets[0])
    if not recordings:
        fail(f"{treatment} vs {control}: no recordings")

    per_seed = [
        float(b["pooled"]["macro_f1"] - a["pooled"]["macro_f1"])
        for a, b in zip(a_runs, b_runs)
    ]
    delta_f1_2 = float(np.mean([
        b["pooled"]["f1_2"] - a["pooled"]["f1_2"]
        for a, b in zip(a_runs, b_runs)
    ]))
    delta_osd = float(np.mean([
        b["pooled"]["osd_f1"] - a["pooled"]["osd_f1"]
        for a, b in zip(a_runs, b_runs)
    ]))
    rec_a = np.asarray([
        [row["per_recording"][recording]["macro_f1"]
         for recording in recordings]
        for row in a_runs
    ]).mean(axis=0)
    rec_b = np.asarray([
        [row["per_recording"][recording]["macro_f1"]
         for recording in recordings]
        for row in b_runs
    ]).mean(axis=0)
    per_recording_delta = rec_b - rec_a
    rng = np.random.default_rng(BOOT_SEED)
    boot = per_recording_delta[
        rng.integers(0, len(recordings), size=(N_BOOT, len(recordings)))
    ].mean(axis=1)
    ci = [float(np.percentile(boot, 2.5)), float(np.percentile(boot, 97.5))]
    mean_pooled = float(np.mean(per_seed))
    practical_r2 = mean_pooled >= 0.005
    practical_r3 = (
        (delta_f1_2 >= 0.010 or delta_osd >= 0.010)
        and mean_pooled >= NONINF_MARGIN
    )
    operational_ni = mean_pooled >= NONINF_MARGIN
    strict_ni = (
        all(delta >= NONINF_MARGIN for delta in per_seed)
        and ci[0] > NONINF_MARGIN
    )
    if all(delta > 0 for delta in per_seed) and ci[0] > 0:
        evidence = "REAL"
    elif all(delta < 0 for delta in per_seed) and ci[1] < 0:
        evidence = "NEGATIVE"
    elif mean_pooled > 0:
        evidence = "SUGGESTIVE"
    else:
        evidence = "NONE"
    return {
        "control": control,
        "treatment": treatment,
        "per_seed": dict(zip(map(str, SEEDS), per_seed)),
        "mean_pooled_delta": mean_pooled,
        "delta_f1_2": delta_f1_2,
        "delta_osd": delta_osd,
        "bootstrap": {
            "unit": "recording",
            "seeds_averaged_within_recording": True,
            "n_boot": N_BOOT,
            "rng_seed": BOOT_SEED,
            "mean_delta": float(per_recording_delta.mean()),
            "ci95": ci,
            "n_improved": int((per_recording_delta > 0).sum()),
            "n_recordings": len(recordings),
        },
        "evidence": evidence,
        "operational_mean_only_noninferior": operational_ni,
        "strict_noninferior": strict_ni,
        "practical_r2": practical_r2,
        "practical_r3": practical_r3,
        "practical_adoption": practical_r2 or practical_r3,
    }


def decide(primary: Mapping[str, Any]) -> Dict[str, Any]:
    if primary["operational_mean_only_noninferior"] and primary["practical_adoption"]:
        recommendation = "pre012"
        reason = (
            "pre012 passes operational NI and R2/R3 on the pyramid family; "
            "recommend stack_input_mask [1,1,1,0,0,0] in the chain base "
            "before sealing the root (requires explicit approval)"
        )
    elif primary["strict_noninferior"]:
        recommendation = "all6"
        reason = (
            "pre012 is strict-NI but passes neither R2 nor R3; "
            "non-inferiority alone does not justify changing the chain base"
        )
    else:
        recommendation = "all6"
        reason = (
            "pre012 does not transfer to the pyramid family; keep all6 and "
            "record the discordance with the TCN-family graduation result"
        )
    return {
        "chain_base_mask_recommendation": recommendation,
        "reason": reason,
        "phase8_base_mutated": False,
        "complexity_gate_reference": "immutable TCN root (unchanged)",
    }


def certified_result_lineage(snapshot: Mapping[str, Any]) -> Dict[str, Any]:
    lineage: Dict[str, Any] = {}
    for arm in ARMS:
        lineage[arm] = {}
        for seed in SEEDS:
            p = paths_for(arm, seed)
            config = make_config(arm, seed)
            wanted_yaml = canonical_yaml(config)
            wanted_inputs = protocol_inputs(config, snapshot)
            if not lineage_valid(arm, seed, wanted_yaml, wanted_inputs):
                fail(f"report refuses stale/uncertified arm: {tag(arm, seed)}")
            with p["sidecar"].open() as stream:
                sidecar = json.load(stream)
            live = output_fingerprint(arm, seed)
            if sidecar.get("outputs") != live:
                fail(f"report lineage drift: {tag(arm, seed)}")
            lineage[arm][str(seed)] = {
                "result": str(p["result"].relative_to(REPO)),
                "sidecar_sha": sha_file(p["sidecar"]),
                "outputs": live,
            }
    return lineage


def build_report() -> Dict[str, Any]:
    snapshot = source_snapshot()
    lineage = certified_result_lineage(snapshot)
    arm_rows = {
        arm: load_result_rows([paths_for(arm, seed)["result"] for seed in SEEDS])
        for arm in ARMS
    }
    primary = paired_stats(
        "all6", "pre012", arm_rows["all6"], arm_rows["pre012"]
    )
    # Descriptive only: level of the pyramid base against the immutable TCN
    # root.  The root arms predate this runner, so only their result files are
    # SHA-recorded here; no adoption rule reads this block.
    root_paths = [
        RESULTS / f"{ROOT_TAG}_s{seed}_voxsel.json" for seed in SEEDS
    ]
    descriptive = paired_stats(
        ROOT_TAG, "all6", load_result_rows(root_paths), arm_rows["all6"]
    )
    for key in (
        "operational_mean_only_noninferior", "strict_noninferior",
        "practical_r2", "practical_r3", "practical_adoption",
    ):
        descriptive.pop(key, None)
    descriptive["descriptive_only"] = True
    descriptive["root_result_shas"] = {
        str(seed): sha_file(path) for seed, path in zip(SEEDS, root_paths)
    }
    return {
        "protocol": "pyramid-mask-transfer-v1",
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "rules": {
            "noninferiority_margin": NONINF_MARGIN,
            "strict_noninferiority":
                "all seed deltas >= margin and bootstrap lower CI > margin",
            "r2": "mean pooled delta >= +0.005",
            "r3": "delta class-2 or OSD >= +0.010 and macro delta >= -0.002",
        },
        "comparisons": {
            "pre012_vs_all6_pyramid": primary,
            "pyramid_all6_vs_tcn_root": descriptive,
        },
        "decision": decide(primary),
        "source_snapshot": snapshot,
        "lineage": lineage,
    }


