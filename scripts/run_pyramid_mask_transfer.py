def _output_tensors(head: Any, value: Any) -> List[Tuple[str, Any]]:
    import torch

    output = head(value)
    return [
        (name, field)
        for name, field in zip(output._fields, output)
        if isinstance(field, torch.Tensor)
    ]


def check_mask_semantics(models: Mapping[str, Any], seed: int) -> None:
    import torch

    offsets = np.cumsum((0,) + STACK_DIMS)
    generator = torch.Generator().manual_seed(seed + 90_000)
    base = torch.randn(2, 11, sum(STACK_DIMS), generator=generator)
    perturb = torch.randn(2, 11, sum(STACK_DIMS), generator=generator)
    for arm, model in models.items():
        head = model.head.eval()
        mask = ARMS[arm] or (1,) * len(STACK_DIMS)
        included = base.clone()
        excluded = base.clone()
        poisoned = base.clone()
        for index, enabled in enumerate(mask):
            start, end = int(offsets[index]), int(offsets[index + 1])
            if enabled:
                included[..., start:end] += perturb[..., start:end]
            else:
                excluded[..., start:end] += perturb[..., start:end]
                poisoned[..., start:end] = float("nan")
        with torch.no_grad():
            reference = _output_tensors(head, base)
            included_out = _output_tensors(head, included)
            excluded_out = _output_tensors(head, excluded)
            poisoned_out = _output_tensors(head, poisoned)
        included_delta = max(
            (b - a).abs().max().item()
            for (_, a), (_, b) in zip(reference, included_out)
        )
        if included_delta <= 1e-7:
            fail(f"{arm}/seed{seed}: included stacks do not affect output")
        if 0 in mask:
            for (name, a), (_, b), (_, c) in zip(
                reference, excluded_out, poisoned_out
            ):
                if not torch.equal(a, b):
                    fail(
                        f"{arm}/seed{seed}: excluded stacks leak into "
                        f"{name} (max delta "
                        f"{(b - a).abs().max().item():.3e})"
                    )
                if not torch.equal(a, c) or not torch.isfinite(c).all():
                    fail(
                        f"{arm}/seed{seed}: non-finite masked stacks poison "
                        f"{name}"
                    )


def model_equivalence_preflight() -> Dict[str, Any]:
    """Prove both arms share the graph and exact post-init tensor values."""
    import torch

    from src.models.zipcount_v1 import build_model

    summary: Dict[str, Any] = {}
    for seed in SEEDS:
        models: Dict[str, Any] = {}
        rows: Dict[str, Any] = {}
        for arm in ARMS:
            config = make_config(arm, seed)
            reset_initialization_rng(seed)
            model = build_model(copy.deepcopy(config)).cpu()
            missing, unexpected = load_exact_v3_backbone(model)
            for parameter in model.backbone.parameters():
                parameter.requires_grad = False
            models[arm] = model
            rows[arm] = {
                "state_schema": state_schema(model),
                "parameter_schema": parameter_schema(model),
                "state_sha": tensor_digest(model.state_dict().items()),
                "parameter_init_sha": tensor_digest(model.named_parameters()),
                "head_init_sha": tensor_digest(model.head.named_parameters()),
                "total_params": sum(p.numel() for p in model.parameters()),
                "trainable_params": sum(
                    p.numel() for p in model.parameters() if p.requires_grad
                ),
                "missing_after_v3_backbone": missing,
                "unexpected_after_v3_backbone": unexpected,
            }
        reference = rows["all6"]
        invariant_keys = (
            "state_schema", "parameter_schema", "state_sha",
            "parameter_init_sha", "head_init_sha", "total_params",
            "trainable_params", "missing_after_v3_backbone",
            "unexpected_after_v3_backbone",
        )
        for arm, row in rows.items():
            for key in invariant_keys:
                if row[key] != reference[key]:
                    fail(
                        f"matched-init preflight failed for seed {seed}, "
                        f"{arm}: {key} differs from all6"
                    )
        check_mask_semantics(models, seed)
        summary[str(seed)] = {
            key: reference[key]
            for key in (
                "state_sha", "parameter_init_sha", "head_init_sha",
                "total_params", "trainable_params",
                "missing_after_v3_backbone", "unexpected_after_v3_backbone",
            )
        }
        del models
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    return summary


def validate_static_protocol(snapshot: Mapping[str, Any]) -> Dict[str, Any]:
    if not PY.is_file():
        fail(f"Python environment not found: {PY}")
    for path in (INIT, VOX_SEL, PREREG):
        sha_file(path)
    if RUN_ORDER != (
        (1234, "all6"), (1234, "pre012"),
        (2345, "pre012"), (2345, "all6"),
        (3456, "all6"), (3456, "pre012"),
    ):
        fail("locked run order changed")
    for seed in SEEDS:
        configs = {arm: make_config(arm, seed) for arm in ARMS}
        head = configs["all6"]["model"]["head"]
        if (
            head.get("type") != "gated_pyramid_ordinal"
            or head.get("gate_mode") != "global"
            or head.get("ordinal_mode") != "softmax"
            or head.get("use_stage2") is not False
            or "stack_input_mask" in head
        ):
            fail(f"all6/seed{seed}: not the chain's pyramid-minimal a0 head")
        encoder = configs["all6"]["model"]["encoder"]
        if (
            encoder.get("multiscale_alignment") != "average"
            or encoder.get("multiscale_include_final") is not False
        ):
            fail(f"all6/seed{seed}: encoder view differs from the chain base")
        reference = copy.deepcopy(configs["all6"])
        reference["training"].pop("log_dir")
        candidate = copy.deepcopy(configs["pre012"])
        mask = tuple(candidate["model"]["head"].pop("stack_input_mask"))
        candidate["training"].pop("log_dir")
        if mask != PRE012:
            fail(f"pre012/seed{seed}: wrong stack_input_mask {mask}")
        if candidate != reference:
            fail(f"pre012/seed{seed}: config differs beyond stack_input_mask")
        for path in (
            Path(configs["all6"]["data"]["train_manifest"]),
            Path(configs["all6"]["data"]["val_manifest"]),
            Path(configs["all6"]["data"]["stats_file"]),
            Path(configs["all6"]["model"]["encoder"]["checkpoint"]),
        ):
            sha_file(path)
    for seed in SEEDS:
        root = RESULTS / f"{ROOT_TAG}_s{seed}_voxsel.json"
        sha_file(root)
    assert_source_snapshot(snapshot, "during static preflight")
    summary = model_equivalence_preflight()
    assert_source_snapshot(snapshot, "after matched-model preflight")
    return summary


def current_protocol_record(
    snapshot: Mapping[str, Any], preflight_summary: Mapping[str, Any]
) -> Dict[str, Any]:
    return {
        "protocol": "pyramid-mask-transfer-v1",
        "created_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "source_snapshot": snapshot,
        "preflight": preflight_summary,
        "seeds": list(SEEDS),
        "arms": {
            arm: (list(mask) if mask is not None else None)
            for arm, mask in ARMS.items()
        },
        "steps": STEPS,
        "run_order": [list(item) for item in RUN_ORDER],
    }


def install_protocol_record(record: Mapping[str, Any]) -> None:
    path = ART / "protocol_snapshot.json"
    if path.exists():
        try:
            with path.open() as stream:
                old = json.load(stream)
        except (OSError, json.JSONDecodeError):
            old = None
        comparable_old = copy.deepcopy(old)
        comparable_new = json.loads(canonical_json(record))
        if isinstance(comparable_old, dict):
            comparable_old.pop("created_at", None)
        comparable_new.pop("created_at", None)
        if comparable_old == comparable_new:
            return
        destination = unique_stale_path(
            path, dt.datetime.now().strftime("%Y%m%dT%H%M%S")
        )
        path.rename(destination)
        print(f"[stale] protocol snapshot -> {destination.relative_to(REPO)}")
    atomic_json(path, record)


