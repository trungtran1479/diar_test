import json
import os
import torch
import numpy as np
import torchaudio
from torch.utils.data import Dataset
from .feature_extractor import extract_fbank_features

class SpeakerCountDataset(Dataset):
    # sources whose windows must never receive a distillation target
    TEACHER_DENY_SOURCES = ("libri", "musan", "solo", "silence")

    def __init__(self, manifest_path: str, max_duration: float = 30.0, augment: dict = None,
                 teacher_dir: str = "", feature_extractor=extract_fbank_features):
        """
        Args:
            manifest_path: path to the JSONL manifest generated by prepare_data.py
            max_duration: maximum duration in seconds to keep (for memory)
            feature_extractor: callable(waveform, sample_rate) -> [T, 80] features.
                Defaults to the Kaldi-style fbank icefall/Zipformer expects; pass
                extract_nemo_fbank_features when encoder.type == "fastconformer"
                so the frozen backbone sees the feature distribution it was
                pretrained on.
            augment: optional waveform augmentation (train only), e.g.
                {"gain_db": [-28, 3],           # random gain — kills the
                                                 # close-talk/far-field level gap
                 "rir_dir": "/path/simulated_rirs",  # OpenSLR-28
                 "rir_prob": 0.35,
                 # skip RIR for sources that are already far-field/reverberant
                 # (convolving a second RIR onto AMI-SDM = double reverb):
                 "rir_skip_sources": ["ami", "nsf"],
                 # additive noise at a random SNR (far-field simulation).
                 # Speaker-count labels are invariant to added noise.
                 "noise_dir": "/path/musan/noise",
                 "noise_prob": 0.5,
                 "noise_snr_db": [0, 20],
                 "noise_skip_sources": ["ami", "nsf"]}
        """
        self.augment = augment or {}
        self.feature_extractor = feature_extractor
        # Optional knowledge distillation: directory of teacher count-posteriors
        # ("<window id>.npy", [T, 4] @100 Hz). Only windows that HAVE a file get
        # a KD loss — the teacher (DiariZen) is only trustworthy on real
        # conversational audio; on synthetic LibriMix it predicts "1 speaker"
        # for fully-overlapped mixes and would teach the student the opposite
        # of the truth.
        self.teacher_dir = teacher_dir or ""
        self._rir_files = None    # lazily globbed per worker
        self._noise_files = None  # lazily globbed per worker
        self.manifest_path = manifest_path
        # Relative paths in the manifest are resolved against the manifest's directory
        manifest_dir = os.path.dirname(os.path.abspath(manifest_path))
        self.data = []
        with open(manifest_path, 'r') as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                item = json.loads(line)
                for key in ("audio_filepath", "label_filepath"):
                    if key in item and not os.path.isabs(item[key]):
                        cand = os.path.join(manifest_dir, item[key])
                        if os.path.exists(cand):
                            item[key] = cand
                if item.get("duration", 0) <= max_duration:
                    self.data.append(item)
                    
    def __len__(self):
        return len(self.data)
        
    def _mix_tracks(self, item) -> torch.Tensor:
        """On-the-fly mixing from a lhotse-derived recipe:
        tracks = [{source, volume, offset, duration, [source_offset]}, ...].
        Returns mono waveform [1, T] at 16 kHz."""
        import soundfile as sf
        n_total = int(round(item["duration"] * 16000))
        buf = np.zeros(n_total, dtype=np.float32)
        for tr in item["tracks"]:
            start_smp = int(round(tr.get("source_offset", 0.0) * 16000))
            n_want = int(round(tr["duration"] * 16000))
            x, sr = sf.read(tr["source"], dtype="float32",
                            start=start_smp, frames=n_want)
            if x.ndim > 1:
                x = x.mean(axis=1)
            if sr != 16000:
                x = torchaudio.transforms.Resample(sr, 16000)(
                    torch.from_numpy(x).unsqueeze(0)).squeeze(0).numpy()
            x = x * tr.get("volume", 1.0)
            off = int(round(tr["offset"] * 16000))
            end = min(off + len(x), n_total)
            if off < end:
                buf[off:end] += x[:end - off]
        # protect against clipping from summed high-gain tracks
        peak = np.abs(buf).max()
        if peak > 0.99:
            buf = buf * (0.99 / peak)
        return torch.from_numpy(buf).unsqueeze(0)  # [1, T]

    def _apply_augment(self, waveform: torch.Tensor, source: str = "") -> torch.Tensor:
        """Waveform-level augmentation: random RIR convolution + random gain.
        waveform: [1, T] float32 at 16 kHz."""
        if not self.augment:
            return waveform
        import random as _rnd
        x = waveform[0].numpy()

        rir_dir = self.augment.get("rir_dir", "")
        rir_skip = tuple(self.augment.get("rir_skip_sources", []))
        skip_rir = bool(rir_skip) and source.startswith(rir_skip)
        if rir_dir and not skip_rir and _rnd.random() < float(self.augment.get("rir_prob", 0.0)):
            if self._rir_files is None:
                import glob
                self._rir_files = glob.glob(os.path.join(rir_dir, "**", "*.wav"), recursive=True)
            if self._rir_files:
                import soundfile as sf
                from scipy.signal import fftconvolve
                rir, _ = sf.read(_rnd.choice(self._rir_files), dtype="float32")
                if rir.ndim > 1:
                    rir = rir[:, 0]
                # trim leading propagation delay so the convolved audio stays
                # time-aligned with the frame labels
                rir = rir[int(np.argmax(np.abs(rir))):]
                rir = rir / (np.abs(rir).max() + 1e-8)
                x = fftconvolve(x, rir)[:len(x)].astype(np.float32)

        noise_dir = self.augment.get("noise_dir", "")
        noise_skip = tuple(self.augment.get("noise_skip_sources", []))
        skip_noise = bool(noise_skip) and source.startswith(noise_skip)
        if noise_dir and not skip_noise and _rnd.random() < float(self.augment.get("noise_prob", 0.0)):
            if self._noise_files is None:
                import glob
                self._noise_files = glob.glob(os.path.join(noise_dir, "**", "*.wav"), recursive=True)
            if self._noise_files:
                import soundfile as sf
                info = sf.info(_rnd.choice(self._noise_files))
                n_want = int(len(x) * info.samplerate / 16000)
                start = _rnd.randint(0, max(info.frames - n_want, 0))
                noise, nsr = sf.read(info.name, dtype="float32",
                                     start=start, frames=min(n_want, info.frames))
                if noise.ndim > 1:
                    noise = noise.mean(axis=1)
                if nsr != 16000:
                    noise = torchaudio.transforms.Resample(nsr, 16000)(
                        torch.from_numpy(noise).unsqueeze(0)).squeeze(0).numpy()
                if len(noise) < len(x):  # tile short noise clips
                    noise = np.tile(noise, len(x) // max(len(noise), 1) + 1)
                noise = noise[:len(x)]
                snr_lo, snr_hi = self.augment.get("noise_snr_db", [0, 20])
                snr = _rnd.uniform(float(snr_lo), float(snr_hi))
                sig_rms = np.sqrt((x ** 2).mean()) + 1e-8
                noise_rms = np.sqrt((noise ** 2).mean()) + 1e-8
                x = x + noise * (sig_rms / noise_rms) * (10.0 ** (-snr / 20.0))

        gain_db = self.augment.get("gain_db")
        if gain_db:
            g = 10.0 ** (_rnd.uniform(float(gain_db[0]), float(gain_db[1])) / 20.0)
            x = x * g

        peak = np.abs(x).max()
        if peak > 0.99:
            x = x * (0.99 / peak)
        return torch.from_numpy(np.ascontiguousarray(x)).unsqueeze(0)

    def _load_teacher(self, item, n_label_frames: int):
        """Teacher count-posterior [T, 4] @100 Hz, or None if this window has no
        teacher (synthetic sources deliberately have none)."""
        if not self.teacher_dir:
            return None
        # Defence in depth: the teacher (DiariZen) scores ~25% against ground
        # truth on synthetic LibriMix — it calls fully-overlapped mixes "1
        # speaker" — so KD there teaches the exact opposite of the truth. Do not
        # rely on the extraction step having been run with the right --sources
        # filter, or on the output directory being clean.
        if str(item.get("source", "")).startswith(self.TEACHER_DENY_SOURCES):
            return None
        p = os.path.join(self.teacher_dir, str(item.get("id", "")) + ".npy")
        if not os.path.exists(p):
            return None
        post = np.load(p).astype(np.float32)
        if len(post) != n_label_frames:      # off-by-one at window edges
            n = min(len(post), n_label_frames)
            fixed = np.zeros((n_label_frames, post.shape[1]), dtype=np.float32)
            fixed[:n] = post[:n]
            # Any shortfall stays ALL ZERO on purpose: a zero row carries no
            # probability mass, and the KD loss treats "no mass" as "no teacher
            # here". Repeating the last frame instead would invent a confident
            # teacher opinion about audio it never saw, which can slip through
            # the agreement gate.
            post = fixed
        return torch.from_numpy(post)

    def __getitem__(self, idx):
        item = self.data[idx]

        if "tracks" in item:
            waveform = self._mix_tracks(item)  # [1, T], already 16 kHz mono
            waveform = self._apply_augment(waveform, item.get("source", ""))
            features = self.feature_extractor(waveform, sample_rate=16000)  # [T, 80]
            labels = torch.from_numpy(np.load(item["label_filepath"])).long()
            return {
                "id": item.get("id", str(idx)),
                "features": features,
                "labels": labels,
                "teacher": self._load_teacher(item, labels.size(0)),
                "duration": item.get("duration", 0.0),
            }

        # Load audio using soundfile
        import soundfile as sf
        waveform_np, sample_rate = sf.read(item["audio_filepath"])
        waveform = torch.from_numpy(waveform_np).float()
        
        # Resample if needed
        if sample_rate != 16000:
            resampler = torchaudio.transforms.Resample(sample_rate, 16000)
            waveform = resampler(waveform)
            
        # Ensure mono and shape [1, T]
        if waveform.dim() == 1:
            waveform = waveform.unsqueeze(0) # [1, T]
        elif waveform.dim() == 2:
            if waveform.shape[1] == 1 or waveform.shape[1] == 2:
                # [T, C] from soundfile
                waveform = waveform.transpose(0, 1) # [C, T]
            
        if waveform.shape[0] > 1:
            waveform = waveform.mean(dim=0, keepdim=True) # [1, T]

        waveform = self._apply_augment(waveform, item.get("source", ""))
        # Extract features
        features = self.feature_extractor(waveform, sample_rate=16000) # [T, 80]
        
        # Load labels
        labels = np.load(item["label_filepath"]) # [T_label]
        labels = torch.from_numpy(labels).long()
        
        return {
            "id": item.get("id", str(idx)),
            "features": features,
            "labels": labels,
            "teacher": self._load_teacher(item, labels.size(0)),
            "duration": item.get("duration", 0.0)
        }

def collate_fn(batch):
    """Collate function for DataLoader."""
    # Sort by feature length descending
    batch.sort(key=lambda x: x["features"].size(0), reverse=True)
    
    ids = [x["id"] for x in batch]
    features = [x["features"] for x in batch]
    labels = [x["labels"] for x in batch]
    durations = [x["duration"] for x in batch]
    teachers = [x.get("teacher") for x in batch]
    
    # Pad features
    feature_lens = torch.tensor([f.size(0) for f in features], dtype=torch.long)
    padded_features = torch.nn.utils.rnn.pad_sequence(features, batch_first=True, padding_value=0.0)
    
    # Pad labels
    label_lens = torch.tensor([l.size(0) for l in labels], dtype=torch.long)
    padded_labels = torch.nn.utils.rnn.pad_sequence(labels, batch_first=True, padding_value=-100)
    
    # Teacher posteriors (KD): [B, max_T_label, 4] with a per-sample mask —
    # windows without a teacher file (synthetic sources) get mask 0.
    max_lab = padded_labels.size(1)
    padded_teacher = torch.zeros(len(batch), max_lab, 4, dtype=torch.float32)
    teacher_mask = torch.zeros(len(batch), dtype=torch.bool)
    for i, t in enumerate(teachers):
        if t is not None:
            n = min(t.size(0), max_lab)
            padded_teacher[i, :n] = t[:n]
            teacher_mask[i] = True

    return {
        "ids": ids,
        "features": padded_features, # [B, max_T, 80]
        "feature_lens": feature_lens, # [B]
        "labels": padded_labels,      # [B, max_T_label]
        "label_lens": label_lens,     # [B]
        "teacher": padded_teacher,    # [B, max_T_label, 4]
        "teacher_mask": teacher_mask, # [B]
        "durations": durations
    }
